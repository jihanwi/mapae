// Generates web contract bindings from the repo's forge artifacts (out/, via `forge build`) and
// deployment records (deployments/). Run via `npm run codegen` (v3 only) or
// `npm run codegen -- --legacy` (also regenerates the legacy v1/v2 files).
//
// v3  → src/contracts/abisV3.ts + addressesV3.ts (ADDR_V3 from deployments/giwa-sepolia-v3_2.json, the
//   v3.2 stack: new CurveFactory, DojangAnyOf, DojangEASAdapter on top of the reused v3.1 contracts; the
//   v3 / v3.1 records are kept for history, and the treasury still comes from v3_1.json)
// legacy → src/contracts/abis.ts + addresses.ts (ADDR from deployments/giwa-sepolia.json). The
//   legacy pages talk to the already-deployed v1/v2 contracts, whose ABIs differ from the current
//   out/ (e.g. MapaePool.swapKrwForToken was renamed in v3), so the legacy files are NOT
//   regenerated unless --legacy is passed explicitly.
import {readFileSync, writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {dirname, join} from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const artifact = (name) => JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8")).abi;

// ---- v3.2-L1 (C-T2) ----
// src/contracts/abisV3L1.ts: the v3.2-L1 MapaeFactory (optional sponsorship, ProceedsBand,
// proceedsLockOf), its Offering (proceedsLock, ProceedsDistributed) and ProceedsLock. New names, so
// the v3 and legacy files stay as they are. `npm run codegen -- --l1` writes only this file. Note:
// a full v3 run regenerates MapaeFactoryV3Abi from the current out/, i.e. the v3.2-L1 ABI; the web
// calls only quoteConfig on the old factory, which did not change.
const L1_CONTRACTS = {
    MapaeFactoryL1Abi: "MapaeFactory",
    OfferingL1Abi: "Offering",
    ProceedsLockAbi: "ProceedsLock",
};
let abisL1 = "// AUTO-GENERATED by scripts/codegen.mjs (v3.2-L1): do not edit\n";
for (const [exportName, name] of Object.entries(L1_CONTRACTS)) {
    abisL1 += `export const ${exportName} = ${JSON.stringify(artifact(name))} as const;\n`;
}
writeFileSync(join(root, "web", "src", "contracts", "abisV3L1.ts"), abisL1);
console.log("codegen: abisV3L1.ts written");
if (process.argv.includes("--l1")) process.exit(0);

// ---- v3 ----
const V3_CONTRACTS = {
    CurveFactoryAbi: "CurveFactory",
    CurveSaleAbi: "CurveSale",
    FeeRouterAbi: "FeeRouter",
    MapaePoolV3Abi: "MapaePool",
    MembershipTokenV3Abi: "MembershipToken",
    MockKRWV3Abi: "MockKRW",
    MockDojangV3Abi: "MockDojang",
    MapaeFactoryV3Abi: "MapaeFactory",
};
let abisV3 = "// AUTO-GENERATED by scripts/codegen.mjs (v3) — do not edit\n";
for (const [exportName, name] of Object.entries(V3_CONTRACTS)) {
    abisV3 += `export const ${exportName} = ${JSON.stringify(artifact(name))} as const;\n`;
}
writeFileSync(join(root, "web", "src", "contracts", "abisV3.ts"), abisV3);

const v3 = JSON.parse(readFileSync(join(root, "deployments", "giwa-sepolia-v3_2.json"), "utf8"));
// v3.2 reuses the v3.1 FeeRouter, whose platform treasury did not change.
const v31 = JSON.parse(readFileSync(join(root, "deployments", "giwa-sepolia-v3_1.json"), "utf8"));
const addressesV3 = `// AUTO-GENERATED by scripts/codegen.mjs (v3.2) from deployments/giwa-sepolia-v3_2.json — do not edit
export const ADDR_V3 = {
    chainId: ${v3.chainId},
    deployBlock: ${v3.deployBlock}n,
    mockKRW: "${v3.mockKRW}",
    /** Write target only (selfVerify). Reads go through dojangAnyOf. */
    mockDojang: "${v3.mockDojang}",
    /** v3.2 real-name check: official Dojang (adapter) OR MockDojang. */
    dojangAnyOf: "${v3.dojangAnyOf}",
    /** Official GIWA Dojang (TESTNET_FAUCET attester) alone: the "GIWA Dojang" badge. */
    dojangEASAdapter: "${v3.dojangEASAdapter}",
    weth: "${v3.weth}",
    curveFactory: "${v3.curveFactory}",
    mapaeFactory: "${v3.factoryMock}",
    feeRouter: "${v3.feeRouter}",
    poolFactory: "${v3.poolFactory}",
    treasury: "${v31.treasury}",
    /** Most tokens the Dev may receive from the first buy inside the creation tx (5% of supply). */
    devFirstBuyMaxTokens: ${v3.devFirstBuyMaxTokens}n,
    /** Seconds after launch during which only verified wallets may buy (CurveFactory.priorityWindow at deploy). */
    priorityWindow: ${v3.priorityWindow},
} as const;
`;
writeFileSync(join(root, "web", "src", "contracts", "addressesV3.ts"), addressesV3);
console.log("codegen: abisV3.ts + addressesV3.ts written");

if (!process.argv.includes("--legacy")) process.exit(0);

// ---- legacy (v1/v2), unchanged generation ----

const CONTRACTS = [
    "MapaeFactory",
    "Offering",
    "MembershipToken",
    "MockKRW",
    "MockDojang",
    "RedeemManager",
    "Sponsorship",
    "MapaePool",
];

let abis = "// AUTO-GENERATED by scripts/codegen.mjs — do not edit\n";
for (const name of CONTRACTS) {
    const art = JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8"));
    abis += `export const ${name}Abi = ${JSON.stringify(art.abi)} as const;\n`;
}
writeFileSync(join(root, "web", "src", "contracts", "abis.ts"), abis);

const dep = JSON.parse(readFileSync(join(root, "deployments", "giwa-sepolia.json"), "utf8"));
const demo = JSON.parse(readFileSync(join(root, "deployments", "demo-state.json"), "utf8"));
const addresses = `// AUTO-GENERATED by scripts/codegen.mjs — do not edit
export const ADDR = {
    chainId: ${dep.chainId},
    mockKRW: "${dep.mockKRW}",
    mockDojang: "${dep.mockDojang}",
    factory: "${dep.factoryMock}",
    poolFactory: "${dep.poolFactory}",
    dojangEASAdapter: "${dep.dojangEASAdapter}",
    offeringA: "${demo.offeringA}",
    offeringB: "${demo.offeringB}",
} as const;
// Approx. block of the current deployment — event scans start here (GIWA caps
// eth_getLogs at 100k blocks per request, so scans are chunked from this base).
export const DEPLOY_BLOCK = 31443000n;
`;
writeFileSync(join(root, "web", "src", "contracts", "addresses.ts"), addresses);
console.log("codegen: abis.ts + addresses.ts written");
