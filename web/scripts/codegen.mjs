// Generates web contract bindings from the repo's forge artifacts (out/, via `forge build`) and
// deployment records (deployments/). Run via `npm run codegen` (L1 + v3) or `npm run codegen -- --l1`
// (L1 only).
//
// v3  → src/contracts/abisV3.ts + addressesV3.ts (ADDR_V3 from deployments/giwa-sepolia-v3_6.json since
//   W-T61 (v3.6 CurveFactory: scheduled start, verified-only); v3_5.json from W-T54 (v3.5, the priority
//   holding cap); before that from giwa-sepolia-v3_2.json, the
//   v3.2 stack: new CurveFactory, DojangAnyOf, DojangEASAdapter on top of the reused v3.1 contracts; the
//   v3 / v3.1 records are kept for history, and the treasury still comes from v3_1.json)
// The v1/v2 files (abis.ts, addresses.ts) were removed in W-T32 (decision 57: the v2 demo offerings
//   left the screens; their on-chain records stay, see deployments/giwa-sepolia.json).
import {readdirSync, readFileSync, writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {dirname, join} from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const artifact = (name) => JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8")).abi;

// ---- L1 (C-T2, W-T32, W-T40): the fixed-price offering section ----
// src/contracts/abisV3L1.ts + addressesV3L1.ts (L1_FACTORIES and ADDR_L1 from every L1 deployment record).
// The L1 file owns every ABI the offering section needs that L0 does not: MapaeFactory (full),
// Offering, ProceedsLock, RedeemManager, Sponsorship, MapaeVesting. Pool, token, FeeRouter and the
// mocks are the same contracts as L0 and come from abisV3.ts.
//
// No cross overwrite: the two deployed MapaeFactory contracts differ (the old one, 0xC0E2…45A9, is
// L0's quote registry; the L1 ones are v3.2-L1 and later), so abisV3.ts keeps only the quote-registry slice of
// the factory ABI (L0_FACTORY_ITEMS, identical on both) as MapaeFactoryV3Abi, and the full current
// ABI goes to MapaeFactoryL1Abi. Regenerating either file never changes what the other screen calls.
// `npm run codegen -- --l1` writes only the L1 files.
const L1_CONTRACTS = {
    MapaeFactoryL1Abi: "MapaeFactory",
    OfferingL1Abi: "Offering",
    ProceedsLockAbi: "ProceedsLock",
    RedeemManagerL1Abi: "RedeemManager",
    SponsorshipL1Abi: "Sponsorship",
    MapaeVestingL1Abi: "MapaeVesting",
};
let abisL1 = "// AUTO-GENERATED by scripts/codegen.mjs (L1): do not edit\n";
for (const [exportName, name] of Object.entries(L1_CONTRACTS)) {
    abisL1 += `export const ${exportName} = ${JSON.stringify(artifact(name))} as const;\n`;
}
writeFileSync(join(root, "web", "src", "contracts", "abisV3L1.ts"), abisL1);

// W-T40: every L1 deployment record (deployments/giwa-sepolia-v*_l1.json) is read. The offering section
// lists the offerings of every L1 factory; new offerings open only on the current (newest) one.
// Contracts the records share must be the same address, or codegen fails.
export const L1_SHARED = ["dojangAnyOf", "mockKRW", "poolFactory", "buybackVault", "proceedsLockDeployer", "membershipTokenDeployer"];
const versionKey = (v) => {
    const m = /^v(\d+)\.(\d+)-L1$/.exec(v);
    if (!m) throw new Error(`unexpected L1 version ${v}`);
    return Number(m[1]) * 1000 + Number(m[2]);
};
/** L1 records, current first; throws when a shared address differs or a version repeats. */
export function l1Records(records) {
    const list = [...records].sort((a, b) => versionKey(b.version) - versionKey(a.version));
    if (list.length === 0) throw new Error("no L1 deployment record");
    for (let i = 1; i < list.length; i++) if (list[i].version === list[i - 1].version) throw new Error(`duplicate L1 record ${list[i].version}`);
    for (const k of L1_SHARED) {
        for (const r of list) {
            if (typeof r[k] !== "string" || r[k].toLowerCase() !== list[0][k].toLowerCase()) throw new Error(`L1 records disagree on ${k} (${r.version} vs ${list[0].version})`);
        }
    }
    return list;
}
const l1Files = readdirSync(join(root, "deployments")).filter((f) => /^giwa-sepolia-v\d+_\d+_l1\.json$/.test(f)).sort();
const l1All = l1Records(l1Files.map((f) => JSON.parse(readFileSync(join(root, "deployments", f), "utf8"))));
const l1 = l1All[0];
// selfVerify target: the MockDojang inside DojangAnyOf (v3.2 record; DojangAnyOf is shared)
const v32 = JSON.parse(readFileSync(join(root, "deployments", "giwa-sepolia-v3_2.json"), "utf8"));
if (l1.dojangAnyOf.toLowerCase() !== v32.dojangAnyOf.toLowerCase()) throw new Error("L1 and v3.2 use different DojangAnyOf");
const firstBlock = l1All.reduce((m, r) => (r.deployBlock < m ? r.deployBlock : m), l1.deployBlock);
const addressesL1 = `// AUTO-GENERATED by scripts/codegen.mjs from deployments/${l1Files.join(", deployments/")}: do not edit
/** Every L1 MapaeFactory, current first. The offering section lists the offerings of all of them;
 *  new offerings open only on the first. deployBlock: the record's first deployment block. */
export const L1_FACTORIES = [
${l1All.map((r) => `    {version: "${r.version}", mapaeFactory: "${r.mapaeFactory}", feeRouter: "${r.feeRouter}", deployBlock: ${r.deployBlock}n},`).join("\n")}
] as const;
/** The current L1 deployment (${l1.version}). */
export const ADDR_L1 = {
    chainId: ${l1.chainId},
    version: "${l1.version}",
    /** First block of the current deployment. */
    deployBlock: ${l1.deployBlock}n,
    /** First block of the oldest L1 deployment: scans over offerings of any factory start here. */
    firstBlock: ${firstBlock}n,
    mapaeFactory: "${l1.mapaeFactory}",
    proceedsLockDeployer: "${l1.proceedsLockDeployer}",
    /** Real-name check of the factory (official Dojang OR MockDojang). */
    dojangAnyOf: "${l1.dojangAnyOf}",
    /** Write target only (selfVerify); reads go through dojangAnyOf. */
    mockDojang: "${v32.mockDojang}",
    /** The factory's payment token. */
    mockKRW: "${l1.mockKRW}",
    poolFactory: "${l1.poolFactory}",
    /** FeeRouter of the current factory (create screen); an offering reads its own feeRouter(). */
    feeRouter: "${l1.feeRouter}",
    buybackVault: "${l1.buybackVault}",
} as const;
`;
writeFileSync(join(root, "web", "src", "contracts", "addressesV3L1.ts"), addressesL1);
console.log("codegen: abisV3L1.ts + addressesV3L1.ts written");
// W-T34: create-form bounds that live as constants in the contracts (Offering, MapaeVesting,
// Sponsorship). Read from src/ (`<type> public constant NAME = VALUE [days|hours];`), so they
// follow the contracts; a missing name fails codegen. Factory bands (guide, proceedsBand, minRaise)
// are read on chain by the page, not here.
const CONSTANTS = {
    Offering: ["MIN_DURATION", "MAX_DURATION", "CANCEL_FREEZE", "SETTLE_TIMEOUT", "MIN_F_BPS", "MAX_F_BPS", "MIN_CREATOR_TOKEN_BPS", "MAX_CREATOR_TOKEN_BPS", "MIN_C_BPS", "MAX_C_BPS", "MAX_SWAP_ROYALTY_BPS", "MAX_SWAP_BURN_BPS"],
    MapaeVesting: ["MIN_VESTING_DURATION", "MAX_VESTING_DURATION", "MIN_CLIFF"],
    Sponsorship: ["MAX_BURN_SHARE_BPS"],
};
const UNIT = {"": 1n, seconds: 1n, minutes: 60n, hours: 3600n, days: 86400n};
export function contractConstants(source, names) {
    const out = {};
    for (const n of names) {
        const m = new RegExp(`\\bpublic\\s+constant\\s+${n}\\s*=\\s*([0-9_]+)\\s*(seconds|minutes|hours|days)?\\s*;`).exec(source);
        if (!m) throw new Error(`constant ${n} not found`);
        out[n] = BigInt(m[1].replaceAll("_", "")) * UNIT[m[2] ?? ""];
    }
    return out;
}
let bounds = "// AUTO-GENERATED by scripts/codegen.mjs (L1) from src/*.sol constants: do not edit\n";
bounds += "// Seconds for durations, bps for shares.\n";
for (const [contract, names] of Object.entries(CONSTANTS)) {
    const vals = contractConstants(readFileSync(join(root, "src", `${contract}.sol`), "utf8"), names);
    bounds += `export const ${contract.toUpperCase()}_CONSTS = {\n${Object.entries(vals).map(([k, v]) => `    ${k}: ${v}n,`).join("\n")}\n} as const;\n`;
}
writeFileSync(join(root, "web", "src", "contracts", "offeringBoundsL1.ts"), bounds);
console.log("codegen: offeringBoundsL1.ts written");
if (process.argv.includes("--l1")) process.exit(0);

// ---- v3 ----
const V3_CONTRACTS = {
    CurveFactoryAbi: "CurveFactory",
    CurveSaleAbi: "CurveSale",
    FeeRouterAbi: "FeeRouter",
    MapaePoolV3Abi: "MapaePool",
    MembershipTokenV3Abi: "MembershipToken",
    MockKRWV3Abi: "MockKRW",
    MockDojangV3Abi: "MockDojang",
    MapaeFactoryV3Abi: "MapaeFactory",
};
/** L0 calls only the quote registry of the old MapaeFactory; these items are the same on both deployed
 *  factories, so the L0 ABI never follows later factory changes (see the v3.2-L1 note above). */
const L0_FACTORY_ITEMS = new Set(["quoteConfig", "isQuoteAllowed", "allQuotes", "QuoteAllowed", "QuoteEnabledSet"]);
const v3Abi = (exportName, name) =>
    exportName === "MapaeFactoryV3Abi" ? artifact(name).filter((x) => L0_FACTORY_ITEMS.has(x.name)) : artifact(name);
let abisV3 = "// AUTO-GENERATED by scripts/codegen.mjs (v3) — do not edit\n";
for (const [exportName, name] of Object.entries(V3_CONTRACTS)) {
    abisV3 += `export const ${exportName} = ${JSON.stringify(v3Abi(exportName, name))} as const;\n`;
}
writeFileSync(join(root, "web", "src", "contracts", "abisV3.ts"), abisV3);

// W-T61: the L0 curve factory is v3.6 (scheduled start, verified-only; W-T54 v3.5 before it). It reuses
// the v3.2 stack, whose record still holds MockDojang and the Dojang adapter; the shared addresses must agree.
const v3 = JSON.parse(readFileSync(join(root, "deployments", "giwa-sepolia-v3_6.json"), "utf8"));
for (const k of ["dojangAnyOf", "mockKRW", "factoryMock", "feeRouter", "poolFactory", "weth"]) {
    if (v3[k].toLowerCase() !== v32[k].toLowerCase()) throw new Error(`v3.6 and v3.2 records disagree on ${k}`);
}
// v3.2 reuses the v3.1 FeeRouter, whose platform treasury did not change.
const v31 = JSON.parse(readFileSync(join(root, "deployments", "giwa-sepolia-v3_1.json"), "utf8"));
